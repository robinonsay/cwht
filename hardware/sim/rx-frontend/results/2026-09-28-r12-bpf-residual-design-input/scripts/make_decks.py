"""Write the LTspice decks of the receiver front-end image and half-IF analysis (WP-PDR-19 pre-order item of
TS-012 revision 4, section 7.3). Run: .venv/bin/python hardware/sim/rx-frontend/make_decks.py
Decks go to hardware/sim/rx-frontend/decks/. Every value that is an estimate is labelled in the deck comments.

Filter decks (.ac): each section is simulated as its own two-port between 50 ohm terminations (a 2 V AC source
behind 50 ohm, a 50 ohm load), so V(oK) is S21 of section K. The sections are separated in the receiver by the
MMBFJ310 grounded-gate stages (reverse isolation assumed complete; the J310 tuned drain selectivity is not
credited), so the front-end response is the product of the section S21s, formed by check_bpf.py.
"""
import math, os
import numpy as np
from bpf_design import synth, netlist_block, F0

HERE = os.path.dirname(os.path.abspath(__file__))
DECKS = os.path.join(HERE, "decks")
L_RES = 56e-9          # resonator inductance: hand-wound 24 AWG air coil or Coilcraft 1812SMS-56N (catalog Q min 100, typ 125 at 150 MHz)
QC = 500               # capacitor Q of small C0G parts at 146 MHz (estimate, Low)
LVIA = "5n"            # ground-return inductance per resonator (TS-012 condition: 5 nH ground via)
SEED = 20260928        # Monte Carlo seed (numpy default_rng), fixed so every draw is reproducible
N_MC = 200

HEAD = """* cwht receiver front-end band-pass filter, {title}
* Generated by hardware/sim/rx-frontend/make_decks.py (do not edit by hand). LTspice 26.0.2 via tools/ltspice-batch.sh.
* Topology: shunt parallel-LC resonators, top-C coupling, series-C end coupling (bpf_design.py).
* Resonator L {lres:.0f} nH; coil Q QU (stepped or fixed); capacitor Q {qc} (estimate); ground via {lvia}H per resonator.
"""


def sections(spec, bw):
    return [synth(n, bw, 0.1, L_RES) for n in spec]


def ports(k):
    return [f"V{k} s{k} 0 AC 2", f"R{k}s s{k} i{k} 50", f"R{k}l o{k} 0 50"]


def write(name, lines):
    os.makedirs(DECKS, exist_ok=True)
    p = os.path.join(DECKS, name)
    with open(p, "w") as f:
        f.write("\n".join(lines) + "\n")
    return p


def q_deck(spec, bw, extra_title=""):
    ds = sections(spec, bw)
    tag = "p".join(map(str, spec))
    name = f"bpf_{tag}_bw{bw/1e6:.0f}.net"
    L = [HEAD.format(title=f"sections {'+'.join(map(str, spec))} resonators, design ripple bandwidth {bw/1e6:.0f} MHz, coil Q stepped {extra_title}",
                     lres=L_RES * 1e9, qc=QC, lvia=LVIA)]
    L.append(f".param QC={QC} LVIA={LVIA}")
    L.append(".step param QU list 100 120 150 200")
    for k, d in enumerate(ds, 1):
        L += ports(k)
        L += netlist_block(d, f"b{k}", f"i{k}", f"o{k}")
    L.append(".ac dec 2000 1Meg 1G")
    L.append(".save " + " ".join(f"V(o{k})" for k in range(1, len(ds) + 1)))
    L.append(".options plotwinsize=0 numdgt=15")
    L.append(".end")
    return write(name, L), ds


def leak_deck(spec, bw):
    """Stray feed-through capacitance from input to output of each section (board leakage sensitivity)."""
    ds = sections(spec, bw)
    tag = "p".join(map(str, spec))
    name = f"bpf_{tag}_bw{bw/1e6:.0f}_leak.net"
    L = [HEAD.format(title=f"sections {'+'.join(map(str, spec))}, stray input-to-output capacitance CST stepped per section, coil Q 100",
                     lres=L_RES * 1e9, qc=QC, lvia=LVIA)]
    L.append(f".param QU=100 QC={QC} LVIA={LVIA}")
    L.append("* The stray path is driven by an ideal copy of the section input voltage times SGN (+1 or -1), so each")
    L.append("* stray value is run with both phases of the leakage relative to the filter path (a leak of unknown phase).")
    L.append(".step param CST list 0.003p 0.01p 0.03p 0.1p")
    L.append(".step param SGN list -1 1")
    for k, d in enumerate(ds, 1):
        L += ports(k)
        L += netlist_block(d, f"b{k}", f"i{k}", f"o{k}")
        L.append(f"Est{k} x{k} 0 i{k} 0 {{SGN}}")
        L.append(f"Cst{k} x{k} o{k} {{CST}}")
    L.append(".ac lin 721 118Meg 154Meg")
    L.append(".save " + " ".join(f"V(o{k})" for k in range(1, len(ds) + 1)))
    L.append(".options plotwinsize=0 numdgt=15")
    L.append(".end")
    return write(name, L), ds


def mc_deck(spec, bw, mode="A"):
    """Monte Carlo on the TS-012 tolerance condition: coil Q 100, coupling and end capacitors x U(0.8, 1.2)
    (20 % tolerance; sub-pF C0G parts are +/-0.1 to 0.25 pF, i.e. 10 to 30 %), 5 nH ground via, and a residual
    resonator tuning error after the owner's NanoVNA alignment of x U(0.994, 1.006) on L (+/-0.3 % in frequency,
    about +/-0.44 MHz; estimate). Draws are made here with a fixed seed and written as LTspice table() lookups.
    mode "A": the TS-012 condition, coupling and end capacitors x U(0.8, 1.2).
    mode "B": the part specification proposed in the analysis record: coupling capacitors C0G with +/-0.1 pF
    (B tolerance) plus +/-0.05 pF of board stray, taken as U(-0.15, +0.15) pF absolute; end capacitors C0G
    +/-0.25 pF (C tolerance) as U(-0.25, +0.25) pF absolute. Coil Q 100, vias and residual tuning as in A."""
    ds = sections(spec, bw)
    rng = np.random.default_rng(SEED)
    draws = {}
    tabs = []

    def tolname(kind, prefix, i):
        key = f"m{kind}{prefix}{i}"
        if key not in draws:
            d = ds[int(prefix[1:]) - 1]
            if kind in ("ck", "cs") and mode == "B":
                c = d["ck"][i] if kind == "ck" else (d["cs_in"] if i == 0 else d["cs_out"])
                a = (0.15e-12 if kind == "ck" else 0.25e-12) / c
                v = rng.uniform(1 - a, 1 + a, N_MC)
            elif kind in ("ck", "cs"):
                v = rng.uniform(0.8, 1.2, N_MC)
            elif kind == "l":
                v = rng.uniform(0.994, 1.006, N_MC)
            else:
                v = np.ones(N_MC)
            draws[key] = v
        return key

    body = []
    for k, d in enumerate(ds, 1):
        body += ports(k)
        body += netlist_block(d, f"b{k}", f"i{k}", f"o{k}", tol=tolname)
    for key, v in draws.items():
        # continuation lines keep each physical line short; split only between pairs
        items = [f"{i+1},{x:.5f}" for i, x in enumerate(v)]
        lines = []
        cur = ""
        for it in items:
            if len(cur) + len(it) > 900:
                lines.append(cur)
                cur = ""
            cur = (cur + ", " + it) if cur else it
        lines.append(cur)
        tabs.append(f".param {key}=table(run, " + lines[0] + ("," if len(lines) > 1 else ")"))
        for j, ln in enumerate(lines[1:], 1):
            tabs.append("+ " + ln + ("," if j < len(lines) - 1 else ")"))
    tag = "p".join(map(str, spec))
    name = f"bpf_{tag}_bw{bw/1e6:.0f}_mc{mode}.net"
    cond = "the TS-012 tolerance condition (mode A)" if mode == "A" else "the proposed part specification (mode B)"
    L = [HEAD.format(title=f"sections {'+'.join(map(str, spec))}, Monte Carlo N={N_MC} seed {SEED} on {cond}",
                     lres=L_RES * 1e9, qc=QC, lvia=LVIA)]
    L.append(f".param QU=100 QC={QC} LVIA={LVIA}")
    L.append(f".step param run 1 {N_MC} 1")
    L += tabs
    L += body
    L.append(".ac lin 361 118Meg 154Meg")
    L.append(".save " + " ".join(f"V(o{k})" for k in range(1, len(ds) + 1)))
    L.append(".options plotwinsize=0 numdgt=15")
    L.append(".end")
    np.savez(os.path.join(DECKS, name.replace(".net", "_draws.npz")), **draws)
    return write(name, L), ds


C_FLOOR = 1e-21        # value written for a zero port or stray capacitance (1e-9 pF, electrically absent)


def _table_lines(key, vals):
    """One .param KEY=table(run, 1,v1, 2,v2, ...) statement with continuation lines under 900 characters."""
    items = [f"{i+1},{x:.9g}" for i, x in enumerate(vals)]
    lines, cur = [], ""
    for it in items:
        if len(cur) + len(it) > 900:
            lines.append(cur)
            cur = ""
        cur = (cur + ", " + it) if cur else it
    lines.append(cur)
    out = [f".param {key}=table(run, " + lines[0] + ("," if len(lines) > 1 else ")")]
    for j, ln in enumerate(lines[1:], 1):
        out.append("+ " + ln + ("," if j < len(lines) - 1 else ")"))
    return out


def values_deck(name, title, spec, cases, freqs, bw=6e6):
    """Deck with one .step run per case (revision 2 runs r08 to r10). Each case is a dict holding, for every
    section k (1-based): the tolerance multipliers by their netlist_block names (mcsb{k}0, mckb{k}i, mlb{k}i;
    the L entries already include any alignment), and the port and leak values RS{k}, RL{k}, CI{k}, CL{k},
    CST{k}, SGN{k}; plus QU. Missing multipliers are 1, missing ports 50 ohm and 0 F, missing leak 0.
    freqs: the .ac list frequencies (Hz). Written with table(run, ...) like mc_deck, so every value is in the
    deck. The port and stray capacitors are written with C_FLOOR when zero."""
    ds = sections(spec, bw)
    n = len(cases)
    keys = set()
    body = []
    for k, d in enumerate(ds, 1):
        def tol(kind, prefix, i):
            if kind not in ("ck", "cs", "l"):
                return None
            key = f"m{kind}{prefix}{i}"
            keys.add(key)
            return key
        body += [f"V{k} s{k} 0 AC 2", f"R{k}s s{k} i{k} {{RS{k}}}", f"C{k}i i{k} 0 {{CI{k}}}",
                 f"R{k}l o{k} 0 {{RL{k}}}", f"C{k}l o{k} 0 {{CL{k}}}"]
        body += netlist_block(d, f"b{k}", f"i{k}", f"o{k}", tol=tol)
        body += [f"Est{k} x{k} 0 i{k} 0 {{SGN{k}}}", f"Cst{k} x{k} o{k} {{CST{k}}}"]
        keys |= {f"RS{k}", f"RL{k}", f"CI{k}", f"CL{k}", f"CST{k}", f"SGN{k}"}
    keys.add("QU")
    dflt = lambda key: (50.0 if key[:2] in ("RS", "RL") else 100.0 if key == "QU" else
                        C_FLOOR if key[:2] in ("CI", "CL") or key.startswith("CST") else 0.0 if key.startswith("SGN") else 1.0)
    tabs = []
    for key in sorted(keys):
        vals = []
        for c in cases:
            v = float(c.get(key, dflt(key)))
            if (key[:2] in ("CI", "CL") or key.startswith("CST")) and v == 0.0:
                v = C_FLOOR
            vals.append(v)
        tabs += _table_lines(key, vals)
    L = [HEAD.format(title=f"sections {'+'.join(map(str, spec))}, {title}", lres=L_RES * 1e9, qc=QC, lvia=LVIA)]
    L.append("* Ports: source RS{k} with shunt CI{k} at the section input, load RL{k} with shunt CL{k}; stray CST{k}")
    L.append("* from an ideal copy SGN{k} x V(i{k}) to the output (SGN 0: no leak). Values per run in the tables below.")
    L.append(f".param QC={QC} LVIA={LVIA}")
    L.append(f".step param run 1 {n} 1" if n > 1 else ".param run=1")
    L += tabs
    L += body
    fl = [f"{x/1e6:.4f}Meg" for x in freqs]
    for j in range(0, len(fl), 12):
        L.append((".ac list " if j == 0 else "+ ") + " ".join(fl[j:j + 12]))
    L.append(".save " + " ".join(f"V(o{k})" for k in range(1, len(ds) + 1)))
    L.append(".options plotwinsize=0 numdgt=15")
    L.append(".end")
    return write(name, L), ds


# 1N5711 model: community library model (search result 2026-09-28, e.g. evenator/LTSpice-Libraries standard.dio);
# checked against MACOM 1N5711 Rev. V3 limits: VF(1 mA) = 0.43 V model vs 0.41 V max; VF(15 mA) = 0.62 V vs 1.00 V
# max; Cjo 1.8 pF vs 2.0 pF max. Used for relative (balance) results only.
D5711 = "D(IS={{19.7n*{m}}} N=1.51 BV=70 IBV=50n RS={{6.27*{r}}} CJO={{1.8p*{c}}} VJ=.75 M=.333 XTI=2 EG=.69 TT=10.8p)"


def ring_deck(cases, name, title):
    """Diode-ring mixer (four 1N5711W, two trifilar BN-43-202 transformers), LO a Si5351 square wave (+10 dBm
    fundamental available from 50 ohm, 1 ns edges, duty D), RF tone from 50 ohm, IF from the RF-transformer
    centre tap into 50 ohm (the diplexer is idealised as a 50 ohm load). cases: list of dicts with keys
    f (tone Hz), p (dBm available), d (LO duty), m1..m4 (Is mult), r1..r4, c1..c4, lb, lc (secondary-half L mults)."""
    n = len(cases)
    def tab(key):
        return f".param {key}=table(run, " + ", ".join(f"{i+1},{c[key]:.6g}" for i, c in enumerate(cases)) + ")"
    L = [f"* cwht receiver: {title}",
         "* Generated by hardware/sim/rx-frontend/make_decks.py. LTspice 26.0.2 via tools/ltspice-batch.sh.",
         "* Transformer windings 4 uH each, k 0.99 (estimate for 2 to 3 trifilar turns on BN-43-202 at VHF, Low).",
         "* LO: Si5351 CLK0, square wave, edges 1 ns (Si5351 datasheet 1 ns typ 20-80 %), duty D (45 to 55 % datasheet),",
         "*     EMF +/-1.571 V behind 50 ohm = +10 dBm fundamental available (TS-012 section 7.3).",
         f".step param run 1 {n} 1"]
    for key in ("f", "p", "d", "m1", "m2", "m3", "m4", "r1", "r2", "r3", "r4", "c1", "c2", "c3", "c4", "lb", "lc"):
        L.append(tab(key))
    L += [".param FLO=136Meg TLO={1/FLO} TR=1n",
          ".param VRF={sqrt(400*10**(p/10-3))}",
          "Vrf srf 0 SINE(0 {VRF} {f})",
          "Rrf srf rf 50",
          "Vlo slo 0 PULSE(-1.571 1.571 0 {TR} {TR} {d*TLO-TR} {TLO})",
          "Rlo slo lo 50",
          "* RF transformer T1: primary rf-0, secondary a-ct1-b",
          "L1a rf 0 4u Rser=0.05",
          "L1b a ct1 {4u*lb} Rser=0.05",
          "L1c ct1 b {4u*lc} Rser=0.05",
          "K1 L1a L1b L1c 0.99",
          "* LO transformer T2: primary lo-0, secondary c-0(ct)-d",
          "L2a lo 0 4u Rser=0.05",
          "L2b c 0 4u Rser=0.05",
          "L2c 0 d 4u Rser=0.05",
          "K2 L2a L2b L2c 0.99",
          "* ring",
          "D1 a c DM1", "D2 c b DM2", "D3 b d DM3", "D4 d a DM4",
          "* IF port: RF-transformer centre tap into 50 ohm",
          "Rif ct1 0 50"]
    for i in range(1, 5):
        L.append(f".model DM{i} " + D5711.format(m=f"m{i}", r=f"r{i}", c=f"c{i}"))
    L += [".save V(ct1)",
          "* Max step 10 ps: the time-step error leaves a response proportional to the input at 8 MHz (a numerical",
          "* floor): -81 dBc at 20 ps and -86 dBc at 5 ps, independent of reltol 1e-6 or 1e-8 (scratch test 2026-09-28).",
          ".tran 0 1.25u 1u 10p",
          ".options plotwinsize=0 numdgt=15 reltol=1e-6 abstol=1e-15 vntol=1e-9",
          ".end"]
    return write(name, L)


def jfet_deck(cases, name, title):
    """Single MMBFJ310 mixer, representative of A4 (no A4 schematic exists): RF on the gate from 50 ohm, LO
    injected at the source through 100 pF, source bias 150 ohm, drain into an 8 MHz tank (1 uH, 396 pF, 330 ohm
    load) from 5 V. LTspice standard.jft J310 model (Linear Systems)."""
    n = len(cases)
    def tab(key):
        return f".param {key}=table(run, " + ", ".join(f"{i+1},{c[key]:.6g}" for i, c in enumerate(cases)) + ")"
    L = [f"* cwht receiver: {title}",
         "* Generated by hardware/sim/rx-frontend/make_decks.py. LTspice 26.0.2 via tools/ltspice-batch.sh.",
         "* Representative A4 JFET mixer (TS-012 revision 1 JFET mixer; component values chosen here, estimate).",
         f".step param run 1 {n} 1" if n > 1 else ".param run=1"]
    for key in ("f", "p", "d"):
        L.append(tab(key))
    L += [".param FLO=136Meg TLO={1/FLO} TR=1n",
          ".param VRF={sqrt(400*10**(p/10-3))}",
          "Vrf srf 0 SINE(0 {VRF} {f})",
          "Rrf srf g 50",
          "Rg g 0 1k",
          "* LO: the same Si5351 square wave as the ring deck (+10 dBm fundamental available from 50 ohm, duty d).",
          "Vlo slo 0 PULSE(-1.571 1.571 0 {TR} {TR} {d*TLO-TR} {TLO})",
          "Rlo slo loc 50",
          "Clo loc s 100p",
          "Rs s 0 150",
          "J1 d g s J310",
          "Ltank vdd d 1u Rser=0.2",
          "Ctank vdd d 396p",
          "Rtank vdd d 330",
          "Vdd vdd 0 5",
          ".model J310 NJF(Beta=3.384m Betatce=-0.5 Vto=-3.409 Vtotc=-2.5m Lambda=17m Is=193.9f Xti=3 Isr=1881f Nr=2 Alpha=7.533u N=1 Rd=1 Rs=1 Cgd=6.2p Cgs=6.2p Fc=0.5 Vk=74.1 M=465m Pb=1 Kf=46340f Af=1 Mfg=Linear_Systems)",
          ".save V(d)",
          ".tran 0 2.25u 2u 10p",
          "* Gear and reltol 1e-5: trapezoidal runs stopped near t = 2 fs (time step too small) and reltol 1e-6 with",
          "* Gear hit the iteration limit (scratch tests 2026-09-28). The zero-RF case measures the numerical floor.",
          ".options plotwinsize=0 numdgt=15 reltol=1e-5 method=gear",
          ".end"]
    return write(name, L)


def ring_cases():
    base = dict(d=0.5, m1=1, m2=1, m3=1, m4=1, r1=1, r2=1, r3=1, r4=1, c1=1, c2=1, c3=1, c4=1, lb=1, lc=1)
    cases = []
    FW, FH = 144e6, 140e6
    cases.append(dict(base, f=FW, p=-30, set=0))
    cases.append(dict(base, f=FH, p=-150, set=0))  # RF at -150 dBm: numerical and LO floor at 8 MHz
    for p in (-40, -30, -20, -10, 0):
        cases.append(dict(base, f=FH, p=p, set=0))
    rng = np.random.default_rng(SEED + 1)
    duties = [0.45, 0.55, 0.45, 0.55]
    for s in range(4):
        mm = dict(base)
        for i in range(1, 5):
            mm[f"m{i}"] = float(rng.uniform(0.8, 1.2))
            mm[f"r{i}"] = float(rng.uniform(0.9, 1.1))
            mm[f"c{i}"] = float(rng.uniform(0.9, 1.1))
        mm["lb"] = float(rng.uniform(0.98, 1.02)); mm["lc"] = float(rng.uniform(0.98, 1.02))
        mm["d"] = duties[s]
        cases.append(dict(mm, f=FW, p=-30, set=s + 1))
        for p in (-20, -10, 0):
            cases.append(dict(mm, f=FH, p=p, set=s + 1))
    return cases


def jfet_cases():
    c = [dict(f=144e6, p=-30, d=0.5, set=0), dict(f=140e6, p=-150, d=0.5, set=0)]
    for p in (-20, -10, -5, 0):
        c.append(dict(f=140e6, p=p, d=0.5, set=0))
    c += [dict(f=144e6, p=-30, d=0.45, set=1), dict(f=140e6, p=-150, d=0.45, set=1)]
    for p in (-20, -10, -5, 0):
        c.append(dict(f=140e6, p=p, d=0.45, set=1))
    # added after cases 2, 4, 6, 8, 10 and 12 failed to converge (-150, -10 and 0 dBm): floor at -100 and
    # -120 dBm, and -15 and -8 dBm drive points, for the matched-duty set
    c += [dict(f=140e6, p=-100, d=0.5, set=0), dict(f=140e6, p=-120, d=0.5, set=0),
          dict(f=140e6, p=-15, d=0.5, set=0), dict(f=140e6, p=-8, d=0.5, set=0)]
    return c


