def check(block, values, lt):
    errors = []
    text = NOTE.read_text() if NOTE.exists() else ""
    for beg, end, comp, what in ((VS_BEGIN, VS_END, block, "verdict set"), (PV_BEGIN, PV_END, values, "proposed values")):
        if beg not in text or end not in text:
            errors.append(f"{what} markers not found in {NOTE}")
            continue
        stated = text[text.index(beg): text.index(end) + len(end)].strip().splitlines()
        computed = comp.strip().splitlines()
        for i in range(max(len(stated), len(computed))):
            s = stated[i] if i < len(stated) else "<missing>"
            c = computed[i] if i < len(computed) else "<missing>"
            if s.strip() != c.strip():
                errors.append(f"{what} line {i + 1}:\n  note:     {s}\n  computed: {c}")
    if not lt.get("ok"):
        errors.append(f"LTspice cross-check not run or failed: {lt.get('msg', lt)}")
    elif lt["maxdiff"] > 0.5:
        errors.append(f"LTspice cross-check {lt['maxdiff']:.3f} K exceeds 0.5 K")
    if errors:
        print(f"CHECK FAIL: {len(errors)} difference(s)")
        for e in errors:
            print(e)
        return 1
    print("CHECK PASS: the record's verdict set and proposed values equal the computed ones; LTspice within 0.5 K")
    return 0


