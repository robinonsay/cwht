def metrics_eval(L: str, v: dict, duty: float | None = None) -> dict:
    d = duty_of(L, v) if duty is None else duty
    net = build(L, 45.0, v)
    T1 = net.steady(1.0)
    Td = net.steady(d)
    ts, xs = net.transient(300.0, 1.0, lambda t: 1.0)
    ij = net.names.index("J2")
    t30, x30 = net.transient(1800.0, 5.0, lambda t: 0.5)
    n25 = build(L, 25.0, v)
    t25, x25 = n25.transient(300.0, 0.5, lambda t: 1.0)
    s5 = m.surfaces(n25, n25.tdict(x25[-1]), v)
    fr4 = m.hot_faces(net, Td, "FR4")
    lm_ss = T1["LM"] if "LM" in T1 else float("nan")
    return dict(duty=d, tj_pk=r.periodic_peak(net, d)[0], case_d=Td["CASE"],
                petg_d=max(m.petg_hot_faces(net, Td, v).values()), bay_d=Td["BAY"], cell_d=Td["CELL"],
                main_d=Td["MAIN"], fr4_d=max(fr4.values()),
                cell30=float(x30[:, net.names.index("CELL")].max()),
                main30=float(x30[:, net.names.index("MAIN")].max()),
                tj_300=float(np.interp(300.0, ts, xs[:, ij])), tj_180=float(np.interp(180.0, ts, xs[:, ij])),
                surf5=max(x for k, x in s5.items() if not k.startswith("SINK (if")),
                lm_ss=lm_ss, case_ss=T1["CASE"], tj_ss=T1["J2"])


def swept_params():
    return [k for k, p in PC.items() if p.low != p.high and p.cls != "R" and k not in SENSOR_PARAMS]


def tornado(L: str, params=None):
    base_v = vals()
    base = metrics_eval(L, base_v)
    rows = []
    for p in (params or swept_params()):
        prm = PC[p]
        if p in P_ADD and not LAYOUTS[L]["lm_sink"] and p in ("r_lm_if", "c_lm"):
            continue  # LM2940 inputs have no effect without L-2
        lo = metrics_eval(L, dict(base_v, **{p: prm.low}))
        hi = metrics_eval(L, dict(base_v, **{p: prm.high}))
        for k in list(METRICS) + ["duty"]:
            if isinstance(base[k], float) and math.isnan(base[k]):
                continue
            rows.append(dict(layout=L, metric=k, param=p, cls=prm.cls, base_value=prm.value, low=prm.low,
                             high=prm.high, out_base=base[k], out_low=lo[k], out_high=hi[k],
                             swing=abs(hi[k] - lo[k])))
    return base, rows


def bands_from(rows, exclude=frozenset()):
    out = {}
    for x in rows:
        if x["param"] in exclude:
            continue
        b = out.setdefault((x["layout"], x["metric"]), dict(layout=x["layout"], metric=x["metric"], up2=0.0,
                                                              dn2=0.0, items=[]))
        up = max(0.0, x["out_low"] - x["out_base"], x["out_high"] - x["out_base"])
        dn = max(0.0, x["out_base"] - x["out_low"], x["out_base"] - x["out_high"])
        b["up2"] += up * up
        b["dn2"] += dn * dn
        b["items"].append((max(up, dn), x["param"], x["cls"]))
    for b in out.values():
        b["up"], b["dn"] = math.sqrt(b["up2"]), math.sqrt(b["dn2"])
        b["items"].sort(reverse=True)
        b["top"] = "; ".join(f"{p} [{c}] {s:.1f} K" for s, p, c in b["items"][:3])
    return out


# ------------------------------------------------------------------------------------------ closed loop
def reading_cf(T: dict, v: dict) -> float:
    return T["CASE"] - v["ntc_frac_cf"] * (T["CASE"] - T["SINK"])


def reading_sink(T: dict, v: dict) -> float:
    return T["SINK"]


def closed_loop(net: m.Net, v: dict, trip: float, hyst: float, tau: float, reading, demand, t_end: float,
                dt: float = 0.1, x0: dict | None = None, every: int = 10):
    """Closed-loop transient with one over-temperature protection: the sensor reading follows reading(T)
    through a first-order lag tau; at reading >= trip the RF ends t_resp later; it re-arms below trip - hyst.
    demand(t) is the operator's key. Returns the maxima of every node and the traces (every `every` steps)."""
    n = len(net.names)
    C = np.array([net.cap[k] for k in net.names])
    x = np.array([x0[k] for k in net.names]) if x0 else np.full(n, net.t_amb)
    a_f = 1.0 - math.exp(-dt / tau)
    s = reading(net.tdict(x), v)
    inhibited, t_off = False, None
    steps = int(round(t_end / dt))
    xmax = x.copy()
    ts, xs, rd, ky = [0.0], [x.copy()], [s], [0.0]
    n_offs = 0
    trips = []
    rf_prev = False
    for k in range(1, steps + 1):
        t = k * dt
        want = demand(t - 0.5 * dt) > 0.5
        rf = want and not (inhibited and t_off is not None and t - 0.5 * dt >= t_off)
        G, b = net._matrix(net.tdict(x))
        x = np.linalg.solve(G + np.diag(C / dt), C / dt * x + net.power(1.0 if rf else 0.0) + b)
        s = s + a_f * (reading(net.tdict(x), v) - s)
        if not inhibited and s >= trip:
            inhibited, t_off = True, t + v["t_resp"]
            trips.append(t)
        elif inhibited and s < trip - hyst:
            inhibited, t_off = False, None
        if rf_prev and not rf and want:
            n_offs += 1
        rf_prev = rf
        xmax = np.maximum(xmax, x)
        if k % every == 0:
            ts.append(t)
            xs.append(x.copy())
            rd.append(s)
            ky.append(1.0 if rf else 0.0)
    return dict(names=list(net.names), t=np.array(ts), x=np.array(xs), reading=np.array(rd), key=np.array(ky),
                max={nm: float(xmax[i]) for i, nm in enumerate(net.names)}, n_offs=n_offs, trips=trips)


def inhibit_cases():
    P = PC
    sens = dict(ntc_frac_cf=P["ntc_frac_cf"].high, tau_ntc_cf=P["tau_ntc_cf"].high)
    adv = dict(sens, a5_rjc2=P["a5_rjc2"].high, a5_bond=P["a5_bond"].high, a5_p1=P["a5_p1"].low, r_feed=0.0)
    return [("nominal", 0.0, {}), ("+3 C tolerance", P["trip_tol"].value, {}),
            ("+3 C, sensor offset and lag adverse", P["trip_tol"].value, sens),
            ("+3 C, sensor, Rth and dissipation adverse", P["trip_tol"].value, adv)]


GOVERNING = "+3 C, sensor offset and lag adverse"


def run_inhibit(L: str, set_c: float, tol: float, ov: dict, t_end: float = 3600.0, demand=None):
    v = vals(ov)
    net = build(L, 45.0, v)
    return closed_loop(net, v, set_c + tol, v["inh_hyst"], v["tau_ntc_cf"], reading_cf,
                       demand or r.demand_cont, t_end), net


def setpoint_for(L: str, tol: float, ov: dict, v0: dict):
    """Largest setpoint on the 0.1 C grid at which the key-held closed loop holds both the junction
    (tj_limit) and the module case (case_guid): bisection between a holding and a failing value, then the
    next 0.1 C up is confirmed to fail."""
    lim_j, lim_c = v0["tj_limit"], v0["case_guid"]

    def holds(sp):
        res, _ = run_inhibit(L, sp, tol, ov)
        return res["max"]["J2"] <= lim_j and res["max"]["CASE"] <= lim_c, res
    lo, hi = 600, 950  # tenths of a degree C: 60.0 C holds, 95.0 C fails (checked below)
    ok_lo, res_lo = holds(lo / 10)
    ok_hi, _ = holds(hi / 10)
    if not ok_lo or ok_hi:
        raise RuntimeError(f"setpoint bracket 60 to 95 C does not bracket the limit for {L}, {ov}")
    while hi - lo > 1:
        mid = (lo + hi) // 2
        ok, res = holds(mid / 10)
        if ok:
            lo, res_lo = mid, res
        else:
            hi = mid
    ok_up, _ = holds((lo + 1) / 10)
    return lo / 10, res_lo, not ok_up


def inhibit_study(L: str, v0: dict):
    rows, traces = [], {}
    cases = inhibit_cases()
    sets = {}
    for name, tol, ov in cases:
        s, res, largest = setpoint_for(L, tol, ov, v0)
        sets[name] = (s, res, largest)
    x_prop = sets[GOVERNING][0]  # the proposed setpoint: sensor adverse at the +3 C edge (as the TS-012 note)
    for name, tol, ov in cases:
        res, net = run_inhibit(L, x_prop, tol, ov)
        v = vals(ov)
        rows.append(dict(layout=L, case=name, tol=tol, overrides=";".join(f"{k}={x:g}" for k, x in ov.items()),
                         setpoint_case=sets[name][0], setpoint_largest=sets[name][2], x_prop=x_prop,
                         tj_max=res["max"]["J2"], case_max=res["max"]["CASE"], sink_max=res["max"]["SINK"],
                         bay_max=res["max"]["BAY"], n_offs=res["n_offs"], p_pa=net.meta["p_pa"],
                         lm_max=res["max"].get("LM", float("nan"))))
        traces[name] = res
    return rows, traces, x_prop


def backstop_study(L: str, v0: dict):
    """REQ-SYS-181 alone (the REQ-SYS-118 inhibit and the duty cap defeated, e.g. firmware hung with the key
    held): the sink NTC trips at the +3 C upper edge (98 C) and re-arms below it less the comparator
    hysteresis. Returns the maxima against the RA07M1317M ratings; also the adverse dissipation case."""
    out = []
    for name, ov in (("nominal", {}), ("Rth and dissipation adverse",
                                        dict(a5_rjc2=PC["a5_rjc2"].high, a5_bond=PC["a5_bond"].high,
                                             a5_p1=PC["a5_p1"].low, r_feed=0.0, tau_ntc_sink=PC["tau_ntc_sink"].high))):
        v = vals(ov)
        net = build(L, 45.0, v)
        res = closed_loop(net, v, v["trip_hw"] + v["trip_tol"], v["hw_hyst"], v["tau_ntc_sink"], reading_sink,
                          r.demand_cont, 3 * 3600.0, dt=0.2, every=10)
        out.append(dict(layout=L, case=name, tj_max=res["max"]["J2"], case_max=res["max"]["CASE"],
                        sink_max=res["max"]["SINK"], lm_max=res["max"].get("LM", float("nan")),
                        n_offs=res["n_offs"], trace=res))
    return out


def cap_pattern(L: str, v0: dict, x_prop: float):
    """The worst pattern the duty cap allows: in every window, one burst of cap_duty x cap_window of held key
    (13 s key-downs re-keyed after 0.5 s), then silence; the inhibit at the proposed setpoint with nominal
    sensor inputs is active. 4 h from a 45 C soak."""
    v = vals()
    W, D = v["cap_window"], v["cap_duty"]

    def demand(t):
        return 1.0 if (t % W) < D * W and r.demand_cont(t % W) > 0.5 else 0.0
    net = build(L, 45.0, v)
    res = closed_loop(net, v, x_prop, v["inh_hyst"], v["tau_ntc_cf"], reading_cf, demand, 4 * 3600.0, dt=0.2,
                      every=25)
    # PETG hot faces along the trace (last hour)
    names = res["names"]
    sel = res["t"] >= 3 * 3600.0
    petg = [max(m.petg_hot_faces(net, dict(zip(names, xx), AMB=net.t_amb), v).values()) for xx in res["x"][sel]]
    res["petg_last_hour_max"] = float(max(petg))
    res["last_hour_max"] = {nm: float(res["x"][sel, i].max()) for i, nm in enumerate(names)}
    res["duty_actual"] = float(res["key"][res["t"] >= 3600.0].mean())
    return res


def duty_limit_S(L: str, v: dict):
    """D-6 alternative: firmware refuses a new key-down while the sink NTC reads above S; S holds 110 C for a
    13 s key-down starting at S (sink rise over 13 s counted without losses, LM2940 heat included). Floored
    to 0.1 C (INSP-112 finding-16 item e)."""
    net = build(L, 45.0, v)
    c = net.cap["SINK"] + net.cap["CASE"] + net.cap.get("LM", 0.0)
    p = net.meta["p_pa"]
    s = v["tj_limit"] - net.meta["p2"] * v["a5_rjc2"] - p * net.meta["r_if"] - (p + net.meta.get("p_lm", 0.0)) * ON_S / c
    s = math.floor(s * 10) / 10
    return s, round(s - v["trip_tol"], 1)


# ------------------------------------------------------------------------------------------ bench acceptance
def bench_R(L: str, v: dict, p_b: float) -> float:
    """Model of the bench coupon: the A5-CL network at 25 C with every source removed and p_b on the sink."""
    net = build(L, 25.0, v)
    net.src_on = {"SINK": p_b}
    net.src_off = {"SINK": p_b}
    T = net.steady(1.0)
    return (T["SINK"] - 25.0) / p_b


def bench_acceptance(L: str, bands_ns: dict, v0: dict):
    """Sweep the sink-to-air path through k_orient (which scales the whole catalog conductance) and find the
    in-situ resistance at which the duty-cap junction peak plus the band of the inputs the bench does not
    replace reaches 110 C, and the module case plus its band reaches 90 C."""
    ko = np.round(np.arange(0.9, 2.61, 0.05), 3)
    rows = []
    for k in ko:
        v = vals(dict(k_orient=float(k)))
        net = build(L, 45.0, v)
        d = v["cap_duty"]
        pk = r.periodic_peak(net, d)[0]
        Td = net.steady(d)
        rows.append(dict(k_orient=float(k), R5=bench_R(L, v, 5.0), R10=bench_R(L, v, 10.0), tj_pk=pk,
                         case_d=Td["CASE"], cell_d=Td["CELL"], petg_d=max(m.petg_hot_faces(net, Td, v).values())))
    bj, bc = bands_ns[(L, "tj_pk")]["up"], bands_ns[(L, "case_d")]["up"]
    tj = np.array([x["tj_pk"] for x in rows])
    cs = np.array([x["case_d"] for x in rows])
