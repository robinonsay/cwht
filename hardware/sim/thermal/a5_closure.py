def up1(x):
    return math.ceil(round(x * 10, 6)) / 10


def dn1(x):
    return math.floor(round(x * 10, 6)) / 10


def verdict_set(base, bands, inh_rows, bs_rows, v0):
    out = []
    for cid, text, key, limk, lays, basis in CRITERIA:
        for L in LAYOUTS:
            if lays is not None and L not in lays:
                continue
            x = base[L][key]
            lim = v0[limk]
            b = bands[(L, key)]
            verdict = "FAIL" if x > lim else ("OPEN" if x + b["up"] > lim else "PASS")
            out.append(dict(id=cid, tag=key, criterion=text, basis=basis, layout=L, value=x, limit=lim, margin=lim - x,
                            band_up=b["up"], band_dn=b["dn"], verdict=verdict, drivers=b["top"]))
    k = len(CRITERIA) + 1
    for key, limk, what in (("tj_max", "tj_limit", "Junction"), ("case_max", "case_guid", "Module case")):
        for case in [c[0] for c in inhibit_cases()]:
            for row in inh_rows:
                if row["case"] != case:
                    continue
                x, lim = row[key], v0[limk]
                out.append(dict(id=f"C{k:02d}", tag=f"inh:{key}:{case}", criterion=f"{what}, inhibit at the proposed setpoint, key held: {SHORT[case]}",
                                basis="REQ-SYS-118, HZ-003 K2", layout=row["layout"], value=x, limit=lim,
                                margin=lim - x, band_up=0.0, band_dn=0.0, verdict="FAIL" if x > lim else "PASS",
                                drivers="explicit closed-loop case"))
            k += 1
    for row in inh_rows:
        if row["case"] == GOVERNING:
            x = row["sink_max"]
            lim = v0["trip_hw"] - v0["trip_tol"]
            out.append(dict(id=f"C{k:02d}", tag="inh:sink", criterion="Sink, inhibit at the proposed setpoint, key held: +3 C, sensor adverse",
                            basis="REQ-SYS-181 92 C lower edge", layout=row["layout"], value=x, limit=lim,
                            margin=lim - x, band_up=0.0, band_dn=0.0, verdict="FAIL" if x > lim else "PASS",
                            drivers="explicit closed-loop case"))
    k += 1
    for key, limk, what, basis in (("tj_max", "tch_max", "Channel", "RA07M1317M p.8 rating"),
                                   ("case_max", "tcase_op_max", "Module case", "RA07M1317M p.2 Tcase(OP)"),
                                   ("lm_max", "lm_tj_max", "LM2940 junction", "TI SNVS769J p.4")):
        for row in bs_rows:
            x, lim = row[key], v0[limk]
            out.append(dict(id=f"C{k:02d}", tag=f"bs:{key}:{row['case']}", criterion=f"{what}, only the REQ-SYS-181 cut-off acting at 98 C, key held: {SHORT[row['case']]}",
                            basis=basis, layout=row["layout"], value=x, limit=lim,
                            margin=lim - x, band_up=0.0, band_dn=0.0, verdict="FAIL" if x > lim else "PASS",
                            drivers="explicit closed-loop case"))
            k += 1
    return out


def render_block(vs):
    lays = list(LAYOUTS)
    lines = [VS_BEGIN, "", "| Id | Criterion (basis) | Limit, C | " + " | ".join(lays) + " |",
             "|---|---|---|" + "---|" * len(lays)]
    for cid in dict.fromkeys(x["id"] for x in vs):
        rr = {x["layout"]: x for x in vs if x["id"] == cid}
        first = next(iter(rr.values()))
        cells = []
        for L in lays:
            x = rr.get(L)
            if x is None:
                cells.append("-")
                continue
            band = f" +{up1(x['band_up']):.1f}" if x["band_up"] > 0 else ""
            cells.append(f"{up1(x['value']):.1f}{band} **{x['verdict']}**")
        lines.append(f"| {cid} | {first['criterion']} ({first['basis']}) | {first['limit']:.0f} | " + " | ".join(cells) + " |")
    lines += ["", VS_END]
    return "\n".join(lines)


