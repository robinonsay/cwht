def write_csv(path, rows):
    rows = [{k: x for k, x in rr.items() if k != "trace"} for rr in rows]
    with open(path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(dict.fromkeys(k for rr in rows for k in rr)), restval="")
        w.writeheader()
        for rr in rows:
            w.writerow({k: (f"{x:.4f}" if isinstance(x, float) else x) for k, x in rr.items()})


