def prot_range(p: str):
    lo, hi = PROT_EXT.get(p, (None, None))
    return (PC[p].low if lo is None else lo), (PC[p].high if hi is None else hi)


def screen(fn, base_ov: dict, params, metrics=("J2", "CASE")):
    """One-at-a-time screen of a closed-loop case: fn(ov) returns the node maxima; each input at both ends of
    its range (the protection range for r_feed). Returns the base maxima and one row per input."""
    base = fn(dict(base_ov))
    rows = []
    for p in params:
        lo, hi = prot_range(p)
        rl, rh = fn(dict(base_ov, **{p: lo})), fn(dict(base_ov, **{p: hi}))
        row = dict(param=p, cls=PC[p].cls, value=base_ov.get(p, PC[p].value), low=lo, high=hi)
        for k in metrics:
            row[f"{k}_base"], row[f"{k}_low"], row[f"{k}_high"] = base[k], rl[k], rh[k]
            row[f"{k}_rise"] = max(0.0, rl[k] - base[k], rh[k] - base[k])
        # the adverse end: the one that raises the channel plus the case (metrics[0] + metrics[1])
        s_lo = sum(rl[k] for k in metrics[:2])
        s_hi = sum(rh[k] for k in metrics[:2])
        row["adverse_end"] = lo if s_lo > s_hi else hi
        row["adverse_rise"] = max(0.0, max(s_lo, s_hi) - sum(base[k] for k in metrics[:2]))
        rows.append(row)
    return base, rows


def stack_from(rows, min_rise: float = 1e-3) -> dict:
    return {x["param"]: x["adverse_end"] for x in rows if x["adverse_rise"] > min_rise}


def rss(rows, metric: str) -> float:
    return math.sqrt(sum(x[f"{metric}_rise"] ** 2 for x in rows))


