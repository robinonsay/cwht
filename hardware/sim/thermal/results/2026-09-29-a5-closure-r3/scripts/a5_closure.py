def closed_loop(net: m.Net, v: dict, trip: float, hyst: float, tau: float, reading, demand, t_end: float,
                dt: float = 0.1, x0: dict | None = None, every: int = 10):
    """Closed-loop transient with one over-temperature protection: the sensor reading follows reading(T)
    through a first-order lag tau; at reading >= trip the RF ends t_resp later; it re-arms below trip - hyst.
    demand(t) is the operator's key. Returns the maxima of every node and the traces (every `every` steps)."""
    n = len(net.names)
    C = np.array([net.cap[k] for k in net.names])
    x = np.array([x0[k] for k in net.names]) if x0 else np.full(n, net.t_amb)
    a_f = 1.0 - math.exp(-dt / tau)
    s = reading(net.tdict(x), v)
    inhibited, t_off = False, None
    steps = int(round(t_end / dt))
    xmax = x.copy()
    ts, xs, rd, ky = [0.0], [x.copy()], [s], [0.0]
    kon, k_on = [0.0], 0  # RF-on time counted on every step (revision 2, finding-20), sampled with the traces
    n_offs = 0
    trips = []
    rf_prev = False
    for k in range(1, steps + 1):
        t = k * dt
        want = demand(t - 0.5 * dt) > 0.5
        rf = want and not (inhibited and t_off is not None and t - 0.5 * dt >= t_off)
        G, b = net._matrix(net.tdict(x))
        x = np.linalg.solve(G + np.diag(C / dt), C / dt * x + net.power(1.0 if rf else 0.0) + b)
        s = s + a_f * (reading(net.tdict(x), v) - s)
        if not inhibited and s >= trip:
            inhibited, t_off = True, t + v["t_resp"]
            trips.append(t)
        elif inhibited and s < trip - hyst:
            inhibited, t_off = False, None
        if rf_prev and not rf and want:
            n_offs += 1
        rf_prev = rf
        k_on += 1 if rf else 0
        xmax = np.maximum(xmax, x)
        if k % every == 0:
            ts.append(t)
            xs.append(x.copy())
            rd.append(s)
            ky.append(1.0 if rf else 0.0)
            kon.append(k_on * dt)
    return dict(names=list(net.names), t=np.array(ts), x=np.array(xs), reading=np.array(rd), key=np.array(ky),
                kon=np.array(kon), max={nm: float(xmax[i]) for i, nm in enumerate(net.names)}, n_offs=n_offs,
                trips=trips)


