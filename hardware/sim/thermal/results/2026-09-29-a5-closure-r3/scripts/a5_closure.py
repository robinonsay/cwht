def duty_limit_S(L: str, v: dict):
    """D-6 alternative: firmware refuses a new key-down while the sink NTC reads above S; S holds 110 C for a
    13 s key-down starting at S (sink rise over 13 s counted without losses, LM2940 heat included). Floored
    to 0.1 C (INSP-112 finding-16 item e)."""
    net = build(L, 45.0, v)
    c = net.cap["SINK"] + net.cap["CASE"] + net.cap.get("LM", 0.0)
    p = net.meta["p_pa"]
    s = v["tj_limit"] - net.meta["p2"] * v["a5_rjc2"] - p * net.meta["r_if"] - (p + net.meta.get("p_lm", 0.0)) * ON_S / c
    s = math.floor(s * 10) / 10
    return s, round(s - v["trip_tol"], 1)


