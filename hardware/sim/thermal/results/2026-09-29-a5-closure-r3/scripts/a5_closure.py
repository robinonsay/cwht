def ltspice_check(out: Path, L: str = "A5-CL"):
    d = out / "ltspice"
    d.mkdir(exist_ok=True)
    v = vals()
    net = build(L, 45.0, v)
    duty = v["cap_duty"]
    T = net.steady(duty)
    lin = net.linearized(T)
    deck = d / "thermal_a5cl.net"
    p_avg = net.power(duty)
    lines = [f"* cwht WP-PDR-28a thermal network {L}, electrical analogue (1 V = 1 C, 1 A = 1 W, 1 ohm = 1 K/W, 1 F = 1 J/K)",
             f"* conductances frozen at the Python steady state at the {duty * 100:.0f} % duty cap, 45 C; average power",
             "* generated by hardware/sim/thermal/a5_closure.py; run with tools/ltspice-batch.sh",
             "VAMB amb 0 45"]
    for k, (a, b, g) in enumerate(lin, 1):
        lines.append(f"R{k} {a.lower()} {'amb' if b == 'AMB' else b.lower()} {1.0 / g:.9g}")
    for k, n in enumerate(net.names, 1):
        lines.append(f"C{k} {n.lower()} 0 {net.cap[n]:.9g}")
    for k, (n, p) in enumerate(zip(net.names, p_avg), 1):
        if p != 0.0:
            lines.append(f"I{k} 0 {n.lower()} {p:.9g}")
    lines += [".ic " + " ".join(f"V({n.lower()})=45" for n in net.names), ".tran 0 14400 0 4",
              ".meas tran cell_end FIND V(cell) AT=14400", ".meas tran j2_end FIND V(j2) AT=14400", ".end"]
    deck.write_text("\n".join(lines) + "\n")
    pr = subprocess.run([str(ROOT / "tools/ltspice-batch.sh"), "-t", "240", "-o", str(d), "-b", str(deck)],
                        capture_output=True, text=True)
    (d / "ltspice-batch.stderr.txt").write_text(pr.stdout + pr.stderr)
    if pr.returncode != 0:
        return dict(ok=False, rc=pr.returncode, msg=pr.stderr[-2000:])
    from spicelib import RawRead
    raw = RawRead(str(d / "thermal_a5cl.raw"))
    t_lt = np.abs(np.array(raw.get_trace("time").get_wave(0), dtype=float))
    lnet = m.Net(t_amb=45.0)
    for n in net.names:
        lnet.add(n, net.cap[n])
    for a, b, g in lin:
        lnet.link(a, b, g)
    for n, p in zip(net.names, p_avg):
        lnet.src(n, p)
    ts, xs = lnet.transient(14400.0, 1.0, lambda t: 1.0, every=4)
    fig, ax = plt.subplots(figsize=(9, 5))
    res, maxdiff = {}, 0.0
    for n, c in (("J2", "#c0504d"), ("CASE", "#8064a2"), ("SINK", "#1f77b4"), ("LM", "#7f7f7f"), ("BAY", "#e69f00"),
                 ("MAIN", "#9e480e"), ("CELL", "#2ca02c")):
        y_lt = np.array(raw.get_trace(f"V({n.lower()})").get_wave(0), dtype=float)
        y_py = np.interp(t_lt, ts, xs[:, net.names.index(n)])
        diff = float(np.max(np.abs(y_lt - y_py)[t_lt > 30]))
        maxdiff = max(maxdiff, diff)
        res[n] = dict(lt_end=float(y_lt[-1]), py_end=float(xs[-1, net.names.index(n)]), ss=T[n], maxdiff=diff)
        ax.plot(t_lt / 60, y_lt, color=c, lw=2.5, alpha=0.45, label=f"{n} LTspice")
        ax.plot(ts / 60, xs[:, net.names.index(n)], color=c, lw=1.0, ls="--", label=f"{n} Python")
    ax.set_xlabel(f"time, min (45 C soak, average power of the {duty * 100:.0f} % duty cap)")
    ax.set_ylabel("temperature, C")
    ax.set_title(f"LTspice electrical analogue vs Python solver, {L} linearized at the duty cap\n"
                 f"max |difference| after 30 s = {maxdiff:.3f} K (pass criterion 0.5 K)")
    ax.grid(alpha=0.3)
    ax.legend(fontsize=7, ncol=2)
    fig.tight_layout()
    fig.savefig(out / "cl_ltspice_crosscheck.png", dpi=130)
    plt.close(fig)
    return dict(ok=True, maxdiff=maxdiff, nodes=res, deck_sha256=hashlib.sha256(deck.read_bytes()).hexdigest())


