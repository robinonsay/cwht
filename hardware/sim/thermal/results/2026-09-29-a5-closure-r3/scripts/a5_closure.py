def tornado(L: str, params=None):
    base_v = vals()
    base = metrics_eval(L, base_v)
    rows = []
    for p in (params or swept_params()):
        prm = PC[p]
        if p in P_ADD and not LAYOUTS[L]["lm_sink"] and p in ("r_lm_if", "c_lm"):
            continue  # LM2940 inputs have no effect without L-2
        lo = metrics_eval(L, dict(base_v, **{p: prm.low}))
        hi = metrics_eval(L, dict(base_v, **{p: prm.high}))
        for k in list(METRICS) + ["duty"]:
            if isinstance(base[k], float) and math.isnan(base[k]):
                continue
            rows.append(dict(layout=L, metric=k, param=p, cls=prm.cls, base_value=prm.value, low=prm.low,
                             high=prm.high, out_base=base[k], out_low=lo[k], out_high=hi[k],
                             swing=abs(hi[k] - lo[k])))
    return base, rows


