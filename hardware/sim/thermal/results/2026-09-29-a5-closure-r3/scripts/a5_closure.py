def p_lm(v: dict) -> float:
    """LM2940 dissipation of A5-DC (thermal_model.build, with the PWM relay hold of D-5)."""
    i_coil = v["p_relay"] / 5.0
    return v["p_lm2940"] - i_coil * (1.0 - v["relay_hold"]) * (v["v_pack"] - 0.5 - 5.0)


def build(L: str, t_amb: float, v: dict) -> m.Net:
    """A5-DC network of thermal_model.build, then the lever L-2 if the layout has it: the LM2940 heat
    leaves the MAIN node and enters a new LM node tied to the SINK through RthJC(bot) plus the tab joint."""
    net = m.build("A5-DC", t_amb, v)
    net.meta["cl_layout"] = L
    if LAYOUTS[L]["lm_sink"]:
        p = p_lm(v)
        net.src_on["MAIN"] -= p
        net.src_off["MAIN"] -= p
        net.add("LM", v["c_lm"])
        net.link("LM", "SINK", 1.0 / (v["r_lm_jc"] + v["r_lm_if"]))
        net.src("LM", p, p)
        net.meta["p_lm"] = p
    return net


# ------------------------------------------------------------------------------------------ duty
def duty_limit_coupled(L: str, v: dict, lo: float = 0.10, hi: float = 1.0, tol: float = 0.005) -> float:
    """Largest duty (13 s key-downs, periodic steady state) whose junction peak holds tj_limit, by bisection
    (INSP-112 finding-15: re-found for every input value)."""
    net = build(L, 45.0, v)
    if r.periodic_peak(net, hi)[0] <= v["tj_limit"]:
        return hi
    if r.periodic_peak(net, lo)[0] > v["tj_limit"]:
        return 0.0
    while hi - lo > tol:
        mid = 0.5 * (lo + hi)
        if r.periodic_peak(net, mid)[0] <= v["tj_limit"]:
            lo = mid
        else:
            hi = mid
    return lo


def duty_of(L: str, v: dict) -> float:
    return v["cap_duty"] if LAYOUTS[L]["duty"] == "cap" else duty_limit_coupled(L, v)


