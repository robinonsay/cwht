def backstop_study(L: str, v0: dict):
    """REQ-SYS-181 alone (the REQ-SYS-118 inhibit and the duty cap defeated with the firmware running, key held
    3 h; revision 1, finding-1). The sink NTC trips at the upper edge of N +/-3 C and re-arms below it less the
    comparator hysteresis. Governing state: the sink-NTC lag at its adverse end and every PROT_PATH input stacked
    at the end that raises the channel plus the case (screened at the 98 C edge); band: RSS of every other swept
    input. The proposed N is the largest whole degree at or below the SRR value (95 C) at which the governing
    channel and case plus their bands hold 175 C and 110 C, and the LM2940 125 C."""
    tol = v0["trip_tol"]
    lag = dict(tau_ntc_sink=PC["tau_ntc_sink"].high)
    n_cur = v0["trip_hw"]
    _, prot_rows = screen(bs_max(L, n_cur + tol), lag, PROT_PATH, metrics=("CASE", "J2", "LM"))
    gov = dict(lag, **stack_from(prot_rows))

    def bands(edge):
        _, rows = screen(bs_max(L, edge), gov, rest_params(), metrics=("CASE", "J2", "LM"))
        return rows, dict(CASE=rss(rows, "CASE"), J2=rss(rows, "J2"), LM=rss(rows, "LM"))

    def ok(res, b):
        return (res["max"]["CASE"] + b["CASE"] <= v0["tcase_op_max"] and res["max"]["J2"] + b["J2"] <= v0["tch_max"]
                and res["max"]["LM"] + b["LM"] <= v0["lm_tj_max"])
    rows_cur, b_cur = bands(n_cur + tol)
    n = n_cur
    while not ok(run_backstop(L, n + tol, gov), b_cur) and n > 80:
        n -= 1.0
    for _ in range(10):
        rows_p, b_p = bands(n + tol)
        if ok(run_backstop(L, n + tol, gov), b_p):
            break
        n -= 1.0
    # the next whole degree up is confirmed to fail with its own band (unless the proposal is the SRR value)
    n_up_fails = True
    if n < n_cur:
        _, b_up = bands(n + 1.0 + tol)
        n_up_fails = not ok(run_backstop(L, n + 1.0 + tol, gov), b_up)
        if not n_up_fails:
            raise RuntimeError("REQ-SYS-181 search: the next whole degree up also holds")
    out = []
    for name, edge, ov, b in (("nominal, proposed", n + tol, {}, None), ("governing, proposed", n + tol, gov, b_p),
                              ("governing, SRR 95 C", n_cur + tol, gov, b_cur)):
        res = run_backstop(L, edge, ov)
        ic = res["names"].index("CASE")
        c = res["x"][:, ic]
        t = res["t"]
        above = c > v0["case_guid"]
        t90 = float(t[np.argmax(above)]) if above.any() else float("nan")
        out.append(dict(layout=L, case=name, n_c=edge - tol, edge=edge, tj_max=res["max"]["J2"],
                        case_max=res["max"]["CASE"], sink_max=res["max"]["SINK"], lm_max=res["max"]["LM"],
                        band_tj=b["J2"] if b else 0.0, band_case=b["CASE"] if b else 0.0,
                        band_lm=b["LM"] if b else 0.0, n_offs=res["n_offs"],
                        first_above_90_s=t90, frac_above_90_after_1h=float(above[t >= 3600.0].mean()),
                        trace=res))
    info = dict(n_prop=n, n_cur=n_cur, n_up_fails=n_up_fails, gov=gov, prot_rows=prot_rows, band_rows=rows_p, band_rows_cur=rows_cur,
                b_prop=b_p, b_cur=b_cur)
    return out, info


PAT_DT = 0.2  # time step of the pattern runs


def pattern_key(W: float, duty: float, dt: float = PAT_DT):
    """The key of one window of the worst pattern the cap allows, one entry per solver step: held key (13 s
    key-downs re-keyed after 0.5 s, as closed_loop samples r.demand_cont at the step midpoints) until the RF-on
    time in the window reaches duty x W, then silence. Revision 2 (finding-20): revision 1 cut the burst at
    duty x W of elapsed time, so the 0.5 s re-key gaps left the window short of the cap (29.15 %); counting the
    RF-on time itself makes every window hold exactly the key-down time the cap allows."""
    n = int(round(W / dt))
    allow = int(round(duty * W / dt))
    key = np.zeros(n)
    on = 0
    for i in range(n):
        if on < allow and r.demand_cont((i + 0.5) * dt) > 0.5:
            key[i] = 1.0
            on += 1
    if on != allow:
        raise RuntimeError(f"pattern window holds {on * dt} s of key-down, the cap allows {allow * dt} s")
    return key


def pattern_run(L: str, v: dict, trip: float, duty: float, t_end: float = 4 * 3600.0):
    """In every window, one burst of held key holding exactly duty x window of RF-on time (pattern_key), then
    silence; the inhibit trips at `trip` on the flange NTC (math.inf: not counted). 4 h from a 45 C soak."""
    W = v["cap_window"]
    key = pattern_key(W, duty)
    n = len(key)

    def demand(t):  # closed_loop calls it at the step midpoints
        return key[int(math.floor((t % W) / PAT_DT)) % n]
    net = build(L, 45.0, v)
    res = closed_loop(net, v, trip, v["inh_hyst"], v["tau_ntc_cf"], reading_cf, demand, t_end, dt=PAT_DT, every=25)
    names = res["names"]
    sel = res["t"] >= t_end - 3600.0
    petg = [max(m.petg_hot_faces(net, dict(zip(names, xx), AMB=net.t_amb), v).values()) for xx in res["x"][sel]]
    res["petg_last_hour_max"] = float(max(petg))
    res["last_hour_max"] = {nm: float(res["x"][sel, i].max()) for i, nm in enumerate(names)}
    # key-down fraction after the first hour, from the RF-on time counted on every step (revision 2)
    i1 = int(np.argmin(np.abs(res["t"] - 3600.0)))
    res["duty_actual"] = float((res["kon"][-1] - res["kon"][i1]) / (res["t"][-1] - res["t"][i1]))
    res["burst_s"] = float((np.nonzero(key)[0][-1] + 1) * PAT_DT)
    res["duty_cmd"] = duty
    return res


def cap_pattern(L: str, v0: dict, x_prop: float):
    """Revision 1, finding-3. The box bound of the worst pattern the cap allows is taken with the inhibit NOT
    counted (it only removes heat, and whether it trips depends on the sensor state), at the cap and one grid
    step above it; each box maximum carries the RSS band of the steady box metric at that duty. The inhibit is
    counted only for the usability figures: the key-down fraction at 45 C with the nominal sensor and with the
    sensor at its -3 C edge (trips earliest)."""
    v = vals()
    D, step = v["cap_duty"], v["cap_step"]
    out = {}
    for tag, duty in (("cap", D), ("step", round(D + step, 3))):
        res = pattern_run(L, v, math.inf, duty)
        res["bands"] = box_bands_at(L, duty)
        out[tag] = res
    out["use_nom"] = pattern_run(L, v, x_prop, D)
    out["use_lo"] = pattern_run(L, v, x_prop - v["trip_tol"], D)
    return out


