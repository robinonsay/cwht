def bench_R(L: str, v: dict, p_b: float) -> float:
    """Model of the bench coupon: the A5-CL network at 25 C with every source removed and p_b on the sink."""
    net = build(L, 25.0, v)
    net.src_on = {"SINK": p_b}
    net.src_off = {"SINK": p_b}
    T = net.steady(1.0)
    return (T["SINK"] - 25.0) / p_b


def bench_acceptance(L: str, bands_ns: dict, v0: dict):
    """Sweep the sink-to-air path through k_orient (which scales the whole catalog conductance) and find the
    in-situ resistance at which the duty-cap junction peak plus the band of the inputs the bench does not
    replace reaches 110 C, and the module case plus its band reaches 90 C."""
    ko = np.round(np.arange(0.9, 2.61, 0.05), 3)
    rows = []
    for k in ko:
        v = vals(dict(k_orient=float(k)))
        net = build(L, 45.0, v)
        d = v["cap_duty"]
        pk = r.periodic_peak(net, d)[0]
        Td = net.steady(d)
        rows.append(dict(k_orient=float(k), R5=bench_R(L, v, 5.0), R10=bench_R(L, v, 10.0), tj_pk=pk,
                         case_d=Td["CASE"], cell_d=Td["CELL"], petg_d=max(m.petg_hot_faces(net, Td, v).values())))
    bj, bc = bands_ns[(L, "tj_pk")]["up"], bands_ns[(L, "case_d")]["up"]
    tj = np.array([x["tj_pk"] for x in rows])
    cs = np.array([x["case_d"] for x in rows])
    R5 = np.array([x["R5"] for x in rows])
    R10 = np.array([x["R10"] for x in rows])
    # tj and case rise monotonically with k_orient; interpolate the limit crossings
    kj = float(np.interp(v0["tj_limit"] - bj, tj, ko))
    kc = float(np.interp(v0["case_guid"] - bc, cs, ko))
    k_acc = min(kj, kc)
    r5_acc = bench_R(L, vals(dict(k_orient=k_acc)), 5.0)
    r10_acc = bench_R(L, vals(dict(k_orient=k_acc)), 10.0)
    return dict(rows=rows, band_tj=bj, band_case=bc, k_tj=kj, k_case=kc, k_acc=k_acc,
                R5_acc=math.floor(r5_acc * 100) / 100, R10_acc=math.floor(r10_acc * 100) / 100,
                R5_nom=bench_R(L, vals(), 5.0), R10_nom=bench_R(L, vals(), 10.0),
                R5=R5, R10=R10, ko=ko, tj=tj, cs=cs)


