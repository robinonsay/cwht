def box_bands_at(L: str, duty: float, params=None) -> dict:
    """RSS band of the steady box metrics at a fixed duty (the band of the cap-pattern criteria, revision 1
    finding-3); at the cap it equals the tornado band of the same metrics."""
    base_v = vals()
    base = box_steady(L, base_v, duty)
    up2 = {k: 0.0 for k in base}
    for p in (params or swept_params()):
        lo = box_steady(L, dict(base_v, **{p: PC[p].low}), duty)
        hi = box_steady(L, dict(base_v, **{p: PC[p].high}), duty)
        for k in base:
            u = max(0.0, lo[k] - base[k], hi[k] - base[k])
            up2[k] += u * u
    return dict(base=base, up={k: math.sqrt(x) for k, x in up2.items()})


def bands_from(rows, exclude=frozenset()):
    out = {}
    for x in rows:
        if x["param"] in exclude:
            continue
        b = out.setdefault((x["layout"], x["metric"]), dict(layout=x["layout"], metric=x["metric"], up2=0.0,
                                                              dn2=0.0, items=[]))
        up = max(0.0, x["out_low"] - x["out_base"], x["out_high"] - x["out_base"])
        dn = max(0.0, x["out_base"] - x["out_low"], x["out_base"] - x["out_high"])
        b["up2"] += up * up
        b["dn2"] += dn * dn
        b["items"].append((max(up, dn), x["param"], x["cls"]))
    for b in out.values():
        b["up"], b["dn"] = math.sqrt(b["up2"]), math.sqrt(b["dn2"])
        b["items"].sort(reverse=True)
        b["top"] = "; ".join(f"{p} [{c}] {s:.1f} K" for s, p, c in b["items"][:3])
    return out


