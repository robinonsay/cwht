def check(block, lt):
    """INSP finding-3: the note's stated verdict set must equal the computed one, row for row."""
    errors = []
    text = NOTE.read_text()
    if MARK_BEGIN not in text or MARK_END not in text:
        errors.append(f"verdict-set markers not found in {NOTE}")
    else:
        stated = text[text.index(MARK_BEGIN): text.index(MARK_END) + len(MARK_END)].strip().splitlines()
        computed = block.strip().splitlines()
        for i in range(max(len(stated), len(computed))):
            s = stated[i] if i < len(stated) else "<missing>"
            c = computed[i] if i < len(computed) else "<missing>"
            if s.strip() != c.strip():
                errors.append(f"verdict set line {i + 1}:\n  note:     {s}\n  computed: {c}")
    if not lt.get("ok"):
        errors.append(f"LTspice cross-check not run or failed: {lt.get('msg', lt)}")
    elif lt["maxdiff"] > 0.5:
        errors.append(f"LTspice cross-check {lt['maxdiff']:.3f} K exceeds 0.5 K")
    if errors:
        print("CHECK FAIL: " + str(len(errors)) + " difference(s)")
        for e in errors:
            print(e)
        return 1
    print("CHECK PASS: the note's verdict set equals the computed verdict set; LTspice cross-check within 0.5 K")
    return 0


