def run_layout(L: str):
    v = m.vals()
    res = {"layout": L}
    # 1. REQ-SYS-112 steady, continuous key-down, 45 C
    net = m.build(L, 45.0)
    T = net.steady(1.0)
    res["meta"] = dict(net.meta)
    res["ss45"] = T
    res["tj_ss"] = m.tj(net, T)
    res["petg_ss"] = m.petg_hot_faces(net, T)
    res["fr4_ss"] = m.hot_faces(net, T, "FR4")
    res["walls_ss"] = m.hot_faces(net, T, None)
    n25 = m.build(L, 25.0)
    res["tj_ss25"] = m.tj(n25, n25.steady(1.0))
    res["surf_ss45"] = m.surfaces(net, T)
    # 2. transient from a 45 C soak, continuous key-down, 3 h, 1 s steps
    ts, xs = net.transient(3 * 3600.0, 1.0, lambda t: 1.0, every=1)
    res["tr_cont"] = (ts, xs, list(net.names))
    isk = net.names.index("SINK")
    jn = "J2" if net.meta["fin"] == "A5" else "J"
    ij = net.names.index(jn)
    ic = net.names.index("CELL")
    res["tj_180"] = float(np.interp(180.0, ts, xs[:, ij]))  # HZ-003 K10: a stream ends by 180 s
    res["tj_300"] = float(np.interp(300.0, ts, xs[:, ij]))  # HZ-003 K7: the 5 min continuous design case
    n40 = m.build(L, 40.0)  # HZ-003 K1 states 40 C ambient against REQ-SYS-112's 45 C (INSP finding-5)
    t40, x40 = n40.transient(300.0, 1.0, lambda t: 1.0)
    res["tj_300_40"] = float(x40[-1, n40.names.index(jn)])
    # trip sequence (INSP finding-6): the REQ-SYS-118 inhibit on the sink NTC or on the PA-case NTC (with
    # its offset and lag), the REQ-SYS-181 cut-off on the sink, the 60 C cell trip
    rd = np.array([m.ntc_reading(net, net.tdict(x), v) for x in xs])
    tau = v["tau_ntc_a5"] if net.meta["fin"] == "A5" else v["tau_ntc_a4"]
    rd_lag = lag(ts, rd, tau)
    res["ntc_case_trace"] = rd_lag
    tr = {"inh_sink": first_cross(ts, xs[:, isk], v["trip_fw"]),
          "inh_case": first_cross(ts, rd_lag, v["trip_fw"]),
          "hw_sink": first_cross(ts, xs[:, isk], v["trip_hw"]),
          "cell60": first_cross(ts, xs[:, ic], v["cell_limit"]),
          "tj110": first_cross(ts, xs[:, ij], v["tj_limit"])}
    res["trips"] = tr
    res["tj_at"] = {k: (float(np.interp(t, ts, xs[:, ij])) if t is not None else None) for k, t in tr.items()}
    for place, inh in (("sink", "inh_sink"), ("case", "inh_case")):
        cand = [(tr[k], k) for k in (inh, "hw_sink", "cell60") if tr[k] is not None]
        res[f"first_{place}"] = min(cand) if cand else (None, "none")
    res["t_fw"], res["t_hw"], res["t_tj110"], res["t_cell60"] = tr["inh_sink"], tr["hw_sink"], tr["tj110"], tr["cell60"]
    # 3. 50 % duty (13 s on, 13 s off) from a 45 C soak, 3 h
    ts5, xs5 = net.transient(3 * 3600.0, 0.5, key_duty(0.5), every=2)
    res["tr_50"] = (ts5, xs5)
    i30 = np.searchsorted(ts5, 1800.0)
    im = net.names.index("MAIN")
    res["cell_30"] = float(xs5[: i30 + 1, ic].max())
    res["main_30"] = float(xs5[: i30 + 1, im].max())
    T50 = net.steady(0.5)
    res["ss50"] = T50
    res["petg_ss50"] = m.petg_hot_faces(net, T50)
    pk50, _, _ = periodic_peak(net, 0.5)
    res["tj_pk50"] = pk50
    # 4. REQ-SYS-113: 25 C, 5 min continuous from a 25 C soak
    net25 = m.build(L, 25.0)
    t25, x25 = net25.transient(600.0, 0.5, lambda t: 1.0, every=2)
    res["tr_25"] = (t25, x25, list(net25.names), net25)
    i5 = np.searchsorted(t25, 300.0)
    T5 = net25.tdict(x25[i5])
    res["surf_5min"] = m.surfaces(net25, T5)
    return res


def duty_sweep(L: str):
    net = m.build(L, 45.0)
    rows = []
    for d in np.round(np.arange(0.10, 1.0001, 0.05), 2):
        pk, smax, smin = periodic_peak(net, float(d))
        rows.append(dict(layout=L, duty=float(d), tj_peak=pk, sink_max=smax, sink_min=smin,
                         cell_ss=net.steady(float(d))["CELL"]))
    return rows


def duty_limit(L: str, sweep_rows, v):
    """Firmware duty limit (TS-012 7.3 fallback): refuse a new key-down while the sink NTC reads
    above S. S is set so that a 13 s key-down (the longest the REQ-SYS-055 cutoff allows) starting
    at S keeps the junction <= 110 C, with the sink's rise over 13 s counted without losses. The value
    to program is S less the +3 C tolerance."""
    net = m.build(L, 45.0)
    meta = net.meta
    c = net.cap["SINK"] + net.cap["CASE"]
    p = meta["p_pa"]
    if meta["fin"] == "A5":
        s = v["tj_limit"] - meta["p2"] * v["a5_rjc2"] - p * meta["r_if"] - p * 13.0 / c
    else:
        s = v["tj_limit"] - p * (v["a4_rjc"] + meta["r_cs"]) - (p + v["a4_gva_on_sink"]) * 13.0 / c
    ok = [r for r in sweep_rows if r["tj_peak"] <= v["tj_limit"]]
    dmax = max((r["duty"] for r in ok), default=0.0)
    Td = net.steady(dmax) if dmax > 0 else None
    faces = m.petg_hot_faces(net, Td) if Td else {}
    return dict(setpoint=s, setpoint_tol=s - v["trip_tol"], dmax=dmax,
                dl_petg=max(faces.values()) if faces else np.nan,
                dl_petg_part=max(faces, key=faces.get) if faces else "-",
                dl_fr4=max(m.hot_faces(net, Td, "FR4").values(), default=np.nan) if Td else np.nan,
                dl_cell=Td["CELL"] if Td else np.nan, dl_main=Td["MAIN"] if Td else np.nan,
                dl_bay=Td.get("BAY", Td["MAIN"]) if Td else np.nan, dl_sink=Td["SINK"] if Td else np.nan,
                dl_case=Td["CASE"] if Td else np.nan, dl_faces=m.hot_faces(net, Td, None) if Td else {})


