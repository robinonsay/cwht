def inhibit_cases(fin: str):
    """The REQ-SYS-118 inhibit cases, each (name, tolerance, overrides)."""
    P = m.P
    if fin == "A5":
        sens = dict(ntc_frac_a5=P["ntc_frac_a5"].high, tau_ntc_a5=P["tau_ntc_a5"].high)
        adv = dict(sens, a5_rjc2=P["a5_rjc2"].high, a5_bond=P["a5_bond"].high, a5_p1=P["a5_p1"].low,
                   r_feed=0.0)  # bench supply: no feed drop, the highest module dissipation
    else:
        sens = dict(ntc_frac_a4=P["ntc_frac_a4"].high, tau_ntc_a4=P["tau_ntc_a4"].high)
        adv = dict(sens, a4_rjc=P["a4_rjc"].high, a4_isat=P["a4_isat"].high, a4_r_pad=P["a4_r_pad"].high)
    return [("nominal", 0.0, {}), ("+3 C tolerance", P["trip_tol"].value, {}),
            ("+3 C, sensor offset and lag adverse", P["trip_tol"].value, sens),
            ("+3 C, sensor, Rth and dissipation adverse", P["trip_tol"].value, adv)]


def inhibit_study(L: str):
    fin = L[:2]
    rows, traces = [], {}
    for name, tol, ov in inhibit_cases(fin):
        v = m.vals(ov)
        net = m.build(L, 45.0, v)
        r = m.inhibit_run(net, v, v["trip_fw"], tol, demand_cont, 3600.0)
        r50 = m.inhibit_run(net, v, v["trip_fw"], tol, key_duty(0.5), 3600.0)
        # setpoint that holds 110 C in this case: one secant step from 85 C, then a verifying run
        set1 = v["trip_fw"] - (r["tj_max"] - v["tj_limit"])
        r1 = m.inhibit_run(net, v, set1, tol, demand_cont, 3600.0)
        set2 = set1 - (r1["tj_max"] - v["tj_limit"])
        r2 = m.inhibit_run(net, v, set2, tol, demand_cont, 3600.0)
        set_req = math.floor(set2 * 10) / 10  # rounded down, toward the safe side
        r3 = m.inhibit_run(net, v, set_req, tol, demand_cont, 3600.0)
        while r3["tj_max"] > v["tj_limit"]:  # step down until the verifying run holds 110 C
            set_req = round(set_req - 0.1, 1)
            r3 = m.inhibit_run(net, v, set_req, tol, demand_cont, 3600.0)
        first = r["offs"][0] if r["offs"] else (None, None)
        k_first = int(np.searchsorted(r["t"], first[0])) - 1 if first[0] else None
        offset = float(r["case"][k_first] - r["reading"][k_first]) if k_first else float("nan")
        rows.append(dict(layout=L, case=name, tol=tol, overrides=";".join(f"{k}={x:g}" for k, x in ov.items()),
                         tj_max_cont=r["tj_max"], tj_max_50=r50["tj_max"], t_first_off=first[0],
                         tj_first_off=first[1], case_minus_reading_at_first_off=offset,
                         p_pa=net.meta["p_pa"], setpoint_110=set_req, tj_at_setpoint=r3["tj_max"],
                         n_offs=len(r["offs"])))
        traces[name] = r
    return rows, traces


