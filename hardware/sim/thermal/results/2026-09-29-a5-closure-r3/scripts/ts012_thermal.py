def metrics_eval(L: str, v: dict, dmax: float) -> dict:
    """Every metric of the verdict set for one input set (the 30 min duty metrics use the average power,
    which the tornado differences only)."""
    net = m.build(L, 45.0, v)
    T1 = net.steady(1.0)
    T50 = net.steady(0.5)
    Td = net.steady(dmax)
    ts, xs = net.transient(300.0, 1.0, lambda t: 1.0)
    ij = net.names.index("J2" if net.meta["fin"] == "A5" else "J")
    t30, x30 = net.transient(1800.0, 5.0, lambda t: 0.5)
    n25 = m.build(L, 25.0, v)
    t25, x25 = n25.transient(300.0, 0.5, lambda t: 1.0)
    s5 = m.surfaces(n25, n25.tdict(x25[-1]), v)
    fr4 = m.hot_faces(net, T1, "FR4")
    return dict(
        tj_ss=m.tj(net, T1), tj_pk50=periodic_peak(net, 0.5)[0],
        tj_300=float(np.interp(300.0, ts, xs[:, ij])), tj_180=float(np.interp(180.0, ts, xs[:, ij])),
        case_ss=T1["CASE"], dl_case=Td["CASE"],
        surf5=max(x for k, x in s5.items() if not k.startswith("SINK (if")),
        petg_ss=max(m.petg_hot_faces(net, T1, v).values()), petg_ss50=max(m.petg_hot_faces(net, T50, v).values()),
        dl_petg=max(m.petg_hot_faces(net, Td, v).values()),
        fr4_ss=max(fr4.values()) if fr4 else float("nan"),
        bay_ss=T1.get("BAY", T1["MAIN"]), dl_bay=Td.get("BAY", Td["MAIN"]),
        cell30=float(x30[:, net.names.index("CELL")].max()), main30=float(x30[:, net.names.index("MAIN")].max()),
        cell_ss50=T50["CELL"], dl_cell=Td["CELL"], dl_main=Td["MAIN"])


def levers():
    """Section 4.1 levers (INSP finding-8): extrusion vertical (the catalog condition, k_orient 1.0) and the best
    guard (eta_guard_dc 0.95), junction steady at the corner, design-change layouts."""
    out = []
    for L in ("A5-DC", "A4-DC"):
        for name, ov in (("base", {}), ("extrusion vertical, k_orient 1.0", dict(k_orient=1.0)),
                         ("guard effectiveness 0.95", dict(eta_guard_dc=0.95))):
            v = m.vals(ov)
            net = m.build(L, 45.0, v)
            out.append(dict(layout=L, lever=name, tj_ss=m.tj(net, net.steady(1.0))))
    return out


def swept_params():
    return [k for k, p in m.P.items() if p.low != p.high and p.cls != "R" and k not in SENSOR_PARAMS]


def tornado_all(L: str, dmax: float):
    base_v = m.vals()
    base = metrics_eval(L, base_v, dmax)
    rows = []
    for p in swept_params():
        prm = m.P[p]
        lo = metrics_eval(L, dict(base_v, **{p: prm.low}), dmax)
        hi = metrics_eval(L, dict(base_v, **{p: prm.high}), dmax)
        for k in METRICS:
            if math.isnan(base[k]):
                continue
            rows.append(dict(layout=L, metric=k, param=p, cls=prm.cls, base_value=prm.value, low=prm.low,
                             high=prm.high, out_base=base[k], out_low=lo[k], out_high=hi[k],
                             swing=abs(hi[k] - lo[k])))
    return base, rows


def bands_from(rows):
    out = {}
    for r in rows:
        key = (r["layout"], r["metric"])
        b = out.setdefault(key, dict(layout=r["layout"], metric=r["metric"], up2=0.0, dn2=0.0, items=[]))
        up = max(0.0, r["out_low"] - r["out_base"], r["out_high"] - r["out_base"])
        dn = max(0.0, r["out_base"] - r["out_low"], r["out_base"] - r["out_high"])
        b["up2"] += up * up
        b["dn2"] += dn * dn
        b["items"].append((max(up, dn), r["param"], r["cls"]))
    for b in out.values():
        b["up"], b["dn"] = math.sqrt(b["up2"]), math.sqrt(b["dn2"])
        b["items"].sort(reverse=True)
        b["top"] = "; ".join(f"{p} [{c}] {x:.1f} K" for x, p, c in b["items"][:3])
    return out


