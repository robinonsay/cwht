def up1(x):  # round up to 0.1 (toward an upper limit: conservative)
    return math.ceil(round(x * 10, 6)) / 10


def dn1(x):
    return math.floor(round(x * 10, 6)) / 10


def verdict_set(results, limits, bands, inh_rows):
    out = []
    for cid, text, key, lim, lays, basis in CRITERIA:
        for L in results:
            if lays is not None and L not in lays:
                continue
            x = exact_value(key, results[L], limits[L])
            b = bands[(L, key)]
            verdict = "FAIL" if x > lim else ("OPEN" if x + b["up"] > lim else "PASS")
            out.append(dict(id=cid, criterion=text, basis=basis, layout=L, value=x, limit=lim, margin=lim - x,
                            band_up=b["up"], band_dn=b["dn"], verdict=verdict, drivers=b["top"]))
    for cid, case in INH_CRIT:
        for r in inh_rows:
            if r["case"] != case:
                continue
            x = r["tj_max_cont"]
            out.append(dict(id=cid, criterion=f"Junction bound by the 85 C inhibit on the PA-case NTC, {case}",
                            basis="REQ-SYS-118, HZ-003 K2 and C4", layout=r["layout"], value=x, limit=110.0,
                            margin=110.0 - x, band_up=0.0, band_dn=0.0, verdict="FAIL" if x > 110.0 else "PASS",
                            drivers="explicit case (closed-loop run)"))
    return out


def render_verdict_block(vs):
    """The verdict-set table the note states (conservative rounding: value up, margin down)."""
    lays = list(dict.fromkeys(r["layout"] for r in vs))
    lines = [MARK_BEGIN, "",
             "| Id | Criterion | Limit, C | " + " | ".join(lays) + " |",
             "|---|---|---|" + "---|" * len(lays)]
    ids = list(dict.fromkeys(r["id"] for r in vs))
    for cid in ids:
        rr = {r["layout"]: r for r in vs if r["id"] == cid}
        first = next(iter(rr.values()))
        cells = []
        for L in lays:
            r = rr.get(L)
            if r is None:
                cells.append("-")
                continue
            band = f" +{up1(r['band_up']):.1f}" if r["band_up"] > 0 else ""
            cells.append(f"{up1(r['value']):.1f}{band} **{r['verdict']}**")
        crit = first["criterion"].replace("Junction bound by the 85 C inhibit on the PA-case NTC, ", "Inhibit bound, ")
        lines.append(f"| {cid} | {crit} ({first['basis']}) | {first['limit']:.0f} | " + " | ".join(cells) + " |")
    lines += ["", MARK_END]
    return "\n".join(lines)


